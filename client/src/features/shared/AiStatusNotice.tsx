import { AlertTriangle, Info, Loader2, RotateCw, Wrench } from 'lucide-react';
import type { AiStatus } from '../../hooks/useAiStatus.js';
import { refreshAiStatus } from '../../hooks/useAiStatus.js';

/**
 * Honest, prominent reporting of AI configuration state. Never fakes an AI
 * response — when the key is missing, the built-in local template engine is
 * clearly labeled as such so nothing is passed off as model output.
 */
export function AiStatusNotice({ status }: { status: AiStatus }) {
  if (status.state === 'loading') {
    return (
      <p className="flex items-center gap-2 text-sm text-slate" role="status">
        <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
        Checking AI availability…
      </p>
    );
  }

  if (status.state === 'ready') {
    return (
      <p className="flex items-center gap-2 text-sm text-success" role="status">
        <Info className="h-4 w-4" aria-hidden="true" />
        AI planning assistant is available.
      </p>
    );
  }

  if (status.state === 'local') {
    return (
      <div
        role="status"
        className="flex items-start gap-3 rounded-xl border border-slate/30 bg-midnight/5 px-4 py-3 text-sm text-midnight-2"
      >
        <Wrench className="mt-0.5 h-4 w-4 shrink-0 text-slate" aria-hidden="true" />
        <span>
          <strong className="font-semibold">Running in local mode.</strong> No AI API key is
          configured, so plans, menus, invitations and suggestions are built by Eventra&rsquo;s
          built-in template engine from your own event details — not generated by an AI model. Add a
          Gemini API key to the server to unlock AI-authored responses.
        </span>
      </div>
    );
  }

  if (status.state === 'unconfigured') {
    return (
      <div
        role="alert"
        className="flex items-start gap-3 rounded-xl border border-warning/30 bg-warning-soft px-4 py-3 text-sm text-warning"
      >
        <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
        <span>
          <strong className="font-semibold">AI planning is not configured.</strong> A Gemini API key
          has not been set on the server, so generation is unavailable. All manual planning tools —
          budget, timeline, tasks, vendors and reports — continue to work normally.
        </span>
      </div>
    );
  }

  return (
    <div
      role="alert"
      className="flex items-start gap-3 rounded-xl border border-danger/25 bg-danger-soft px-4 py-3 text-sm text-danger"
    >
      <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
      <span className="flex-1">
        <strong className="font-semibold">Cannot reach the Eventra AI server.</strong>{' '}
        {status.message}
      </span>
      <button type="button" className="btn btn-secondary btn-sm" onClick={refreshAiStatus}>
        <RotateCw className="h-3.5 w-3.5" aria-hidden="true" />
        Retry
      </button>
    </div>
  );
}
